import { chromium } from 'playwright-core';
const B='http://localhost:5210';
const b=await chromium.launch({args:['--no-sandbox']});
const p=await b.newPage({viewport:{width:1440,height:1100}});
await p.goto(B+'/catalog',{waitUntil:'networkidle',timeout:120000});
await p.waitForTimeout(4500);
await p.screenshot({path:'/home/user/shots/data-catalog.png'});
console.log('فهرستِ نرم‌افزارها گرفته شد');
await p.goto(B+'/blog',{waitUntil:'networkidle'}); await p.waitForTimeout(3000);
await p.screenshot({path:'/home/user/shots/data-blog.png'});
console.log('وبلاگ گرفته شد');
// ورود و صفحهٔ بارگیری‌ها
await p.goto(B+'/login',{waitUntil:'domcontentloaded'}); await p.waitForTimeout(2500);
const ins=p.locator('input');
await ins.nth(0).fill('casey.demo@example.com');
await ins.nth(1).fill('Password123!');
await p.locator('button').filter({hasText:/ورود|ادامه/}).first().click().catch(async()=>{await p.locator('button[type=submit]').first().click();});
await p.waitForTimeout(4000);
console.log('نشانی پس از ورود:', p.url().replace(B,'')||'/');
await p.goto(B+'/dashboard/downloads',{waitUntil:'networkidle'}); await p.waitForTimeout(3500);
await p.screenshot({path:'/home/user/shots/data-downloads.png'});
console.log('صفحهٔ بارگیری‌ها گرفته شد — طولِ متن:', (await p.innerText('body')).trim().length);
await p.goto(B+'/dashboard/tickets',{waitUntil:'networkidle'}); await p.waitForTimeout(3500);
await p.screenshot({path:'/home/user/shots/data-tickets.png'});
console.log('صفحهٔ تیکت‌ها — طولِ متن:', (await p.innerText('body')).trim().length);
await b.close();
