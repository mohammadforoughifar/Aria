import { chromium } from 'playwright-core';
const b=await chromium.launch({args:['--no-sandbox']});
const ctx=await b.newContext({colorScheme:'dark', viewport:{width:1440,height:1100}});
const p=await ctx.newPage();
const errs=[];
p.on('pageerror',e=>errs.push('PAGEERROR: '+e.message.slice(0,110)));
p.on('console',m=>{if(m.type()==='error'&&!/dotnet\.wasm|ERR_CONNECTION|Failed to load/.test(m.text()))errs.push(m.text().slice(0,110));});
await p.goto('http://localhost:5210/',{waitUntil:'networkidle',timeout:120000});
await p.waitForTimeout(5000);
await p.screenshot({path:'/home/user/shots/white-home.png'});
await p.goto('http://localhost:5210/catalog',{waitUntil:'networkidle'});
await p.waitForTimeout(4000);
await p.screenshot({path:'/home/user/shots/white-catalog.png'});
console.log('تصویرها گرفته شد');
console.log('رنگِ پس‌زمینه:', await p.evaluate(()=>getComputedStyle(document.body).backgroundColor));
console.log('خطاها:', errs.length?[...new Set(errs)].slice(0,4).join(' | ')+' ❌':'هیچ ✅');
await b.close();
